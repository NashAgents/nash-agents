test("turn lease generations survive restart and fence stale task and response writes", async t => {
  t.mock.timers.enable({ apis: ["Date"], now: 1000 });
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "nash-goal-turn-lease-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const file = path.join(dir, "cluster.bin");
  let store = createLocalClusterStore(file);
  await store.saveConversation!({ id: "c", title: "fixture", createdAt: 1, updatedAt: 1, messages: [{ id: "u", conversationId: "c", sender: "user", content: "inspect", timestamp: 1 }] });
  await store.createGoalRun!({ goalRunId: "g", conversationId: "c", userMessageId: "u", rootGoal: "inspect", status: "planning", currentStage: "planning", linkedGraphIds: [], linkedTaskIds: [], requiredExecutionScope: null, reportRevision: 0, revision: 1, createdAt: 1, updatedAt: 1 });
  const first = (await store.claimGoalTurnLease!("g", "u", "owner-a", 100))!;
  assert.equal(first.generation, 1);
  assert.equal(await store.claimGoalTurnLease!("g", "u", "owner-b", 100), null);
  t.mock.timers.tick(101);
  store = createLocalClusterStore(file);
  const second = (await store.claimGoalTurnLease!("g", "u", "owner-b", 100))!;
  assert.equal(second.generation, 2);
  assert.equal(await store.renewGoalTurnLease!("g", first.ownerId, first.generation, 100), false);
  const task = { taskId: "t", nodeId: "n", projectId: "p", goal: "inspect", status: "created" as const, dispatchAttempt: 1, createdAt: 1, updatedAt: 1 };
  await assert.rejects(store.saveTaskWithGoal!(task, "g", first), /lease expired or was superseded/);
  assert.equal(await store.getTask("t"), null);
  await store.saveTaskWithGoal!(task, "g", second);
  const response = { id: "answer", conversationId: "c", sender: "assistant" as const, content: "still running", timestamp: 2, metadata: { goalRunId: "g", goalRunTurnId: "u" } };
  await assert.rejects(store.commitGoalTurnResponse!("g", response, first), /lease expired or was superseded/);
  assert.equal((await store.getConversation!("c"))?.messages.length, 1);
  assert.equal((await store.commitGoalTurnResponse!("g", response, second)).inserted, true);
  assert.equal((await store.commitGoalTurnResponse!("g", { ...response, id: "duplicate" }, first)).inserted, false);
  await assert.rejects(store.saveTaskWithGoal!({ ...task, taskId: "late" }, "g", first), /lease expired or was superseded/);
  const restored = createLocalClusterStore(file);
  assert.equal((await restored.getGoalRun!("g"))?.turnLeaseGeneration, 2);
  assert.equal((await restored.getConversation!("c"))?.messages.length, 2);
});

test("goal runs survive local restart and reject duplicate or stale writes", async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "nash-goal-run-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const file = path.join(dir, "cluster.bin");
  const store = createLocalClusterStore(file);
  const goal: GoalRunRecord = { goalRunId: "g1", conversationId: "c1", userMessageId: "m1", rootGoal: "inspect", status: "planning", linkedGraphIds: [], linkedTaskIds: [], requiredExecutionScope: null, reportRevision: 0, revision: 1, createdAt: 1, updatedAt: 1 };
  assert.equal(await store.createGoalRun!(goal), true);
  assert.equal(await store.createGoalRun!({ ...goal, goalRunId: "g2" }), false);
  const restarted = createLocalClusterStore(file);
  assert.deepEqual(await restarted.getGoalRun!("g1"), goal);
  const next = { ...goal, status: "running" as const, revision: 2 };
  assert.equal(await restarted.updateGoalRun!(next, 1), true);
  assert.equal(await restarted.updateGoalRun!({ ...goal, revision: 2 }, 1), false);
  assert.equal((await restarted.getGoalRun!("g1"))?.status, "running");
  assert.equal((await restarted.listGoalRuns!("another")).length, 0);
  await restarted.saveTaskWithGoal!({ taskId: "t1", runId: "r1", nodeId: "worker", projectId: "p", goal: "scout", status: "created", dispatchAttempt: 1, createdAt: 2, updatedAt: 2 }, "g1");
  const afterCrash = createLocalClusterStore(file);
  assert.deepEqual((await afterCrash.getGoalRun!("g1"))?.linkedTaskIds, ["t1"]);
  assert.equal((await afterCrash.getTask("t1"))?.status, "created");
  await assert.rejects(afterCrash.saveTaskWithGoal!({ taskId: "t2", nodeId: "worker", projectId: "p", goal: "scout", status: "created", dispatchAttempt: 1, createdAt: 2, updatedAt: 2 }, "missing"));
  assert.equal(await createLocalClusterStore(file).getTask("t2"), null);
});

test("new user message and GoalRun persist as one local operation", async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "nash-goal-create-atomic-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const file = path.join(dir, "cluster.bin"), store = createLocalClusterStore(file);
  await store.saveConversation!({ id: "c", title: "fixture", createdAt: 1, updatedAt: 1, messages: [] });
  const conversation = (await store.getConversation!("c"))!;
  conversation.messages.push({ id: "u", conversationId: "c", sender: "user", content: "inspect", timestamp: 2, metadata: { goalRunId: "g" } });
  const goal: GoalRunRecord = { goalRunId: "g", conversationId: "c", userMessageId: "u", rootGoal: "inspect", status: "planning", linkedGraphIds: [], linkedTaskIds: [], requiredExecutionScope: null, reportRevision: 0, revision: 1, createdAt: 2, updatedAt: 2 };
  assert.equal(await store.createGoalRunWithConversation!(goal, conversation, { ownerId: "owner", ttlMs: 60_000 }), true);
  const restarted = createLocalClusterStore(file);
  assert.equal((await restarted.getGoalRun!("g"))?.userMessageId, "u");
  assert.equal((await restarted.getGoalRun!("g"))?.turnLease?.ownerId, "owner");
  assert.equal((await restarted.getGoalRun!("g"))?.turnLease?.turnId, "u");
  assert.equal((await restarted.getConversation!("c"))?.messages[0]?.metadata?.goalRunId, "g");
  assert.equal(await restarted.createGoalRunWithConversation!(goal, conversation), false);
  const missingGoal = { ...goal, goalRunId: "missing", conversationId: "absent" };
  await assert.rejects(restarted.createGoalRunWithConversation!(missingGoal, { ...conversation, id: "absent", messages: [{ ...conversation.messages[0]!, conversationId: "absent", metadata: { goalRunId: "missing" } }] }), /conversation not found/);
  assert.equal(await createLocalClusterStore(file).getGoalRun!("missing"), null);
});

test("clarification message and its turn lease persist together and reject concurrent turns", async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "nash-goal-continue-atomic-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const file = path.join(dir, "cluster.bin"), store = createLocalClusterStore(file);
  await store.saveConversation!({ id: "c", title: "fixture", createdAt: 1, updatedAt: 1, messages: [{ id: "u", conversationId: "c", sender: "user", content: "inspect", timestamp: 1 }] });
  await store.createGoalRun!({ goalRunId: "g", conversationId: "c", userMessageId: "u", rootGoal: "inspect", status: "partially_completed", linkedGraphIds: [], linkedTaskIds: [], requiredExecutionScope: null, reportRevision: 1, revision: 1, createdAt: 1, updatedAt: 1 });
  const first = (await store.getConversation!("c"))!, competing = (await store.getConversation!("c"))!;
  first.messages.push({ id: "u2", conversationId: "c", sender: "user", content: "choice", timestamp: 2, metadata: { goalRunId: "g" } });
  competing.messages.push({ id: "u3", conversationId: "c", sender: "user", content: "other choice", timestamp: 2, metadata: { goalRunId: "g" } });
  const lease = await store.continueGoalRunWithConversation!("g", first, "u2", "owner", 60_000);
  assert.equal(lease?.turnId, "u2");
  assert.equal(await store.continueGoalRunWithConversation!("g", competing, "u3", "other", 60_000), null);
  const restored = createLocalClusterStore(file);
  assert.equal((await restored.getGoalRun!("g"))?.turnLease?.turnId, "u2");
  assert.deepEqual((await restored.getConversation!("c"))?.messages.map(message => message.id), ["u", "u2"]);
});

test("discovery selection is durable even when task dispatch fails before persistence", async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "nash-goal-scope-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const file = path.join(dir, "cluster.bin"), store = createLocalClusterStore(file);
  await registerFixtureNodes(store, "worker");
  await store.createGoalRun!({ goalRunId: "g", conversationId: "c", userMessageId: "u", rootGoal: "inspect", status: "planning", currentStage: "planning", linkedGraphIds: [], linkedTaskIds: [], requiredExecutionScope: null, reportRevision: 0, revision: 1, createdAt: 1, updatedAt: 1 });
  const service = new AutonomousDiscoveryService({ store, registry: { getConnection: () => ({}) } as any, scheduler: { createTask: async () => { throw new Error("injected dispatch failure"); } } as any });
  await defaultTraceContext.run({ projectId: "p", sessionId: "c", traceId: "t", goalRunId: "g" }, () => service.discover("inspect", { nodeIds: ["worker"] }));
  const restored = createLocalClusterStore(file);
  const scope = (await restored.getGoalRun!("g"))?.discoveryScopes?.[0];
  assert.equal(scope?.selectionSource, "explicit_nodes");
  assert.deepEqual(scope?.selectedNodeIds, ["worker"]);
  assert.equal(scope?.snapshot[0]?.catalogRevision, 1);
  assert.equal((await restored.listTasks()).length, 0);
});

test("a turn response and its GoalRun stage survive restart together and are idempotent", async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "nash-goal-turn-atomic-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const file = path.join(dir, "cluster.bin"), store = createLocalClusterStore(file);
  await store.saveConversation!({ id: "c", title: "fixture", createdAt: 1, updatedAt: 1, messages: [{ id: "u", conversationId: "c", sender: "user", content: "inspect", timestamp: 1 }] });
  await store.createGoalRun!({ goalRunId: "g", conversationId: "c", userMessageId: "u", rootGoal: "inspect", status: "planning", currentStage: "planning", linkedGraphIds: [], linkedTaskIds: [], requiredExecutionScope: null, reportRevision: 0, revision: 1, createdAt: 1, updatedAt: 1 });
  const message = { id: "answer", conversationId: "c", sender: "assistant" as const, content: "仍在执行", timestamp: 2, metadata: { goalRunId: "g", goalRunTurnId: "u" } };
  assert.equal((await store.commitGoalTurnResponse!("g", message)).inserted, true);
  const restarted = createLocalClusterStore(file);
  const duplicate = { ...message, id: "answer-duplicate" };
  assert.equal((await restarted.commitGoalTurnResponse!("g", duplicate)).inserted, false);
  const finalStore = createLocalClusterStore(file);
  assert.deepEqual((await finalStore.getConversation!("c"))?.messages.map(item => item.id), ["u", "answer"]);
  const goal = (await finalStore.getGoalRun!("g"))!;
  assert.equal(goal.interimMessageId, "answer");
  assert.equal(goal.interimReport, message.content);
  assert.equal(goal.currentStage, "awaiting_verification");
  assert.equal(goal.reportRevision, 1);
  await assert.rejects(finalStore.commitGoalTurnResponse!("g", { ...message, conversationId: "other" }));
  assert.deepEqual((await finalStore.getConversation!("c"))?.messages.map(item => item.id), ["u", "answer"]);
  const conversation = (await finalStore.getConversation!("c"))!;
  conversation.messages.push({ id: "u2", conversationId: "c", sender: "user", content: "clarification", timestamp: 3, metadata: { goalRunId: "g" } });
  await finalStore.saveConversation!(conversation);
  await finalStore.commitGoalTurnResponse!("g", { ...message, id: "new-answer", timestamp: 4, content: "clarified", metadata: { goalRunId: "g", goalRunTurnId: "u2" } });
  await finalStore.commitGoalTurnResponse!("g", duplicate);
  const afterLateEvent = (await finalStore.getGoalRun!("g"))!;
  assert.equal(afterLateEvent.interimMessageId, "new-answer");
  assert.equal(afterLateEvent.interimReport, "clarified");
  assert.equal(afterLateEvent.reportRevision, 2);
  await assert.rejects(finalStore.commitGoalTurnResponse!("g", { ...message, id: "unlinked", metadata: { goalRunId: "g", goalRunTurnId: "unknown" } }), /not linked/);
  const latestConversation = (await finalStore.getConversation!("c"))!;
  latestConversation.messages.push({ id: "u3", conversationId: "c", sender: "user", content: "another clarification", timestamp: 5, metadata: { goalRunId: "g" } });
  await finalStore.saveConversation!(latestConversation);
  await assert.rejects(finalStore.commitGoalTurnResponse!("g", { ...message, id: "new-answer", metadata: { goalRunId: "g", goalRunTurnId: "u3" } }), /message ID already exists/);
  assert.equal((await finalStore.getGoalRun!("g"))?.interimMessageId, "new-answer");
});
