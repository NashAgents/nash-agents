const allowed = new Set(["MIT", "ISC", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "CC-BY-4.0", "(MPL-2.0 OR Apache-2.0)", "MPL-2.0"]);

export function dependencyInventory(root) {
  const roots = ["", "apps/web"];
  const inventory = [];
  for (const base of roots) {
    const filename = path.posix.join(base, "package-lock.json");
    const bytes = fs.readFileSync(path.join(root, filename));
    const lock = JSON.parse(bytes);
    const packages = Object.entries(lock.packages ?? {}).filter(([location]) => location).map(([location, item]) => ({
      location, name: location.split("node_modules/").at(-1), version: item.version, license: item.license,
      dev: Boolean(item.dev), optional: Boolean(item.optional), integrity: item.integrity,
    })).sort((a, b) => a.location.localeCompare(b.location, "en"));
    for (const item of packages) if (!item.version || !item.integrity || !allowed.has(item.license)) throw { path: filename, line: 1, category: "unreviewed-dependency-license-or-integrity" };
    inventory.push({ base, filename, sha256: sha(bytes), packages });
  }
  return inventory;
}

export function writeDependencyNotices(root) {
  const inventory = dependencyInventory(root);
  const digest = sha(JSON.stringify(inventory));
  const lines = ["# Third-party notices", "", "Generated by `node scripts/dependency-notices.js` from the exact runtime and web lockfiles.", "", "Dependency licenses remain with their respective copyright holders. DOMPurify's dual license is used under its Apache-2.0 option. Development-only and platform-optional packages are listed for build provenance; they are not included as node_modules in the Nash package. Their own npm packages carry their license materials.", "", `<!-- dependency-inventory-sha256: ${digest} -->`, ""];
  const licenseTexts = new Map();
  for (const group of inventory) {
    lines.push(`## ${group.filename}`, "", `Lockfile SHA-256: ${group.sha256}`, "", "| Package | Version | License | Scope |", "| --- | --- | --- | --- |");
    for (const item of group.packages) {
      const url = `https://www.npmjs.com/package/${item.name}/v/${item.version}`;
      lines.push(`| [${item.name}](${url}) | ${item.version} | ${item.license.replaceAll("|", "\\|")} | ${item.dev ? "build/test" : "runtime"}${item.optional ? ", optional" : ""} |`);
      if (item.dev && !["CC-BY-4.0", "MPL-2.0"].includes(item.license)) continue;
      const directory = path.join(root, group.base, item.location);
      if (!fs.existsSync(directory)) { if (item.optional || item.dev) continue; throw { path: path.posix.join(group.base, item.location), line: 1, category: "runtime-dependency-not-installed" }; }
      const metadata = JSON.parse(fs.readFileSync(path.join(directory, "package.json"), "utf8"));
      if (metadata.version !== item.version) throw { path: path.posix.join(group.base, item.location), line: 1, category: "installed-dependency-version-mismatch" };
      const files = fs.readdirSync(directory).filter(name => /^(?:licen[cs]e|copying|notice)(?:[.\-_]|$)/i.test(name) && fs.statSync(path.join(directory, name)).isFile()).sort();
      if (!files.length) {
        const readme = fs.readdirSync(directory).find(name => /^readme(?:\.md|\.txt)?$/i.test(name));
        if (readme && /(?:^|\n)#{1,3}\s*(?:license|licence)/i.test(fs.readFileSync(path.join(directory, readme), "utf8"))) files.push(readme);
      }
      const override = upstreamLicenseOverrides[`${item.name}@${item.version}`];
      if (!files.length && override) files.push("upstream LICENSE");
      if (!files.length) throw { path: path.posix.join(group.base, item.location), line: 1, category: "runtime-license-text-missing" };
      for (const file of files) {
        if (item.license === "(MPL-2.0 OR Apache-2.0)" && /mpl/i.test(file)) continue;
        let text = (file === "upstream LICENSE" ? override.text : fs.readFileSync(path.join(directory, file), "utf8")).replaceAll("\r\n", "\n").trim();
        if (file === "upstream LICENSE" && sha(override.text) !== override.sha256) throw { path: group.filename, line: 1, category: "upstream-license-digest-mismatch" };
        if (/^readme/i.test(file)) text = text.slice(text.search(/(?:^|\n)#{1,3}\s*(?:license|licence)/i)).trim();
        const key = sha(text);
        const entry = licenseTexts.get(key) ?? { packages: new Set(), file, text };
        entry.packages.add(`${item.name}@${item.version}${file === "upstream LICENSE" ? ` (source: ${override.source})` : ""}`); licenseTexts.set(key, entry);
      }
    }
    lines.push("");
  }
  lines.push("## Included runtime license and notice texts", "");
  for (const item of licenseTexts.values()) lines.push(`### ${[...item.packages].sort().join(", ")} — ${item.file}`, "", "````text", item.text, "````", "");
  const content = lines.join("\n");
  const document = `${content}\n<!-- notice-content-sha256: ${sha(content)} -->\n`;
  fs.writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), document);
  return { packages: inventory.reduce((sum, item) => sum + item.packages.length, 0), licenseTexts: licenseTexts.size };
}

export function checkDependencyNotices(root) {
  const inventory = dependencyInventory(root);
  const document = fs.readFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), "utf8");
  const footer = document.match(/\n<!-- notice-content-sha256: ([a-f0-9]{64}) -->\n$/);
  if (!document.includes(`<!-- dependency-inventory-sha256: ${sha(JSON.stringify(inventory))} -->`) || !footer || sha(document.slice(0, footer.index)) !== footer[1]) throw { path: "THIRD_PARTY_NOTICES.md", line: 1, category: "dependency-notices-stale-or-modified" };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = process.argv.includes("--check") ? checkDependencyNotices(process.cwd()) : writeDependencyNotices(process.cwd());
    console.log(JSON.stringify({ audit: "dependency-notices", status: "PASSED", ...result }));
  } catch (error) { console.error(JSON.stringify(error?.category ? error : { path: "THIRD_PARTY_NOTICES.md", line: 1, category: "dependency-notices-failed" })); process.exitCode = 1; }
}
