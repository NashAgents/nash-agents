/**
 * 纯函数式 systemd Unit 渲染器。
 *
 * 设计约束：
 * - 不依赖文件系统、不读取进程环境、不执行任何命令，便于确定性测试；
 * - 所有输入在拼接前完成校验，任何包含换行/控制字符/分号的输入都会被拒绝，
 *   杜绝通过参数注入额外 Unit 指令（如伪造 `ExecStartPre=` 或 `User=`）；
 * - 凭据绝不写入 Unit 正文：密钥只能通过 `EnvironmentFile` 在运行时注入。
 */

export class ServiceUnitValidationError extends Error {
  constructor(public readonly field: string, reason: string) {
    super(`Invalid systemd unit input "${field}": ${reason}`);
    this.name = "ServiceUnitValidationError";
  }
}

export interface BaseUnitInput {
  /** 运行服务的系统账号 */
  user: string;
  /** 运行服务的系统组 */
  group: string;
  /** 安装目录（绝对路径），Unit 的 WorkingDirectory 与 dist/index.js 均由此展开 */
  installDir: string;
  /** Node.js 可执行文件绝对路径 */
  nodePath: string;
  /** 环境变量文件绝对路径（凭据唯一允许来源） */
  envFile: string;
  /** Unit 描述，缺省按角色生成 */
  unitDescription?: string;
}

export interface CoordinatorUnitInput extends BaseUnitInput {
  /** Coordinator 监听地址 */
  host: string;
  /** Coordinator 监听端口 */
  port: number;
  /** Web 控制台静态资源目录（可选，绝对路径） */
  webDist?: string;
  /** 是否在同机拉起本地 Worker（对应 `cluster start --worker`），默认不启用 */
  withWorker?: boolean;
}

export interface WorkerUnitInput extends BaseUnitInput {
  /** 可选：显式覆盖 Coordinator 地址；缺省时由 NASH_HOME 节点身份提供 */
  coordinatorUrl?: string;
}

/** The product process loads its role and credentials from its own protected store. */
export interface ProductUnitInput extends BaseUnitInput {
  /** Declared source revision; runtime artifact attestation remains a separate check. */
  releaseId: string;
  /** Existing local dependencies whose startup should be ordered before Nash. */
  afterServices?: string[];
}

export const DEFAULT_COORDINATOR_DESCRIPTION = "Nash Cluster Coordinator";
export const DEFAULT_WORKER_DESCRIPTION = "Nash Worker";

/** 换行、控制字符、`;` 与 `%` 在 Unit 文件中分别可伪造新指令或触发 Specifier 展开。 */
const FORBIDDEN_UNIT_CHARS = /[\u0000-\u001f\u007f;%]/;
const WHITESPACE = /\s/;
const POSIX_USER_PATTERN = /^(?:[A-Za-z_][A-Za-z0-9_.-]{0,31}|\d{1,10})$/;
const HOST_PATTERN = /^[A-Za-z0-9.:_-]+$/;
const COORDINATOR_URL_PATTERN = /^wss?:\/\/[A-Za-z0-9.:[\]_-]+(?:\/[^\s]*)?$/;

function assertSafeText(field: string, value: unknown): asserts value is string {
  if (typeof value !== "string" || value.length === 0) {
    throw new ServiceUnitValidationError(field, "must be a non-empty string");
  }
  if (FORBIDDEN_UNIT_CHARS.test(value)) {
    throw new ServiceUnitValidationError(
      field,
      'must not contain newlines, control characters, ";" or "%" (unit directive injection risk)'
    );
  }
}

function assertAbsolutePath(field: string, value: unknown): asserts value is string {
  assertSafeText(field, value);
  if (WHITESPACE.test(value)) {
    throw new ServiceUnitValidationError(field, "must not contain whitespace");
  }
  if (/[\\$"']/.test(value)) {
    throw new ServiceUnitValidationError(field, "must not contain systemd expansion or quoting characters");
  }
  if (!value.startsWith("/")) {
    throw new ServiceUnitValidationError(field, "must be an absolute POSIX path");
  }
  const segments = value.split("/");
  if (segments.includes("..")) {
    throw new ServiceUnitValidationError(field, 'must not contain ".." path segments');
  }
  if (value.includes("//") || (value.length > 1 && value.endsWith("/"))) {
    throw new ServiceUnitValidationError(field, "must not contain repeated or trailing separators");
  }
}

function assertUserOrGroup(field: string, value: unknown): asserts value is string {
  assertSafeText(field, value);
  if (!POSIX_USER_PATTERN.test(value)) {
    throw new ServiceUnitValidationError(field, "must be a valid POSIX user or group name");
  }
}

function assertHost(value: unknown): asserts value is string {
  assertSafeText("host", value);
  if (!HOST_PATTERN.test(value)) {
    throw new ServiceUnitValidationError("host", "must be an IP address or hostname");
  }
}

function assertPort(value: unknown): asserts value is number {
  if (typeof value !== "number" || !Number.isInteger(value) || value < 1 || value > 65535) {
    throw new ServiceUnitValidationError("port", "must be an integer between 1 and 65535");
  }
}

function assertDescription(value: unknown, fallback: string): string {
  if (value === undefined) return fallback;
  assertSafeText("unitDescription", value);
  return value;
}

function renderUnitText(params: {
  description: string;
  user: string;
  group: string;
  installDir: string;
  envFile: string;
  execStart: string;
}): string {
  return [
    "# Generated by `nash cluster service install`.",
    "# Secrets belong in EnvironmentFile, never inline in this unit.",
    "",
    "[Unit]",
    `Description=${params.description}`,
    "After=network-online.target",
    "Wants=network-online.target",
    "StartLimitIntervalSec=60s",
    "StartLimitBurst=3",
    "",
    "[Service]",
    "Type=simple",
    `User=${params.user}`,
    `Group=${params.group}`,
    `WorkingDirectory=${params.installDir}`,
    `EnvironmentFile=${params.envFile}`,
    `ExecStart=${params.execStart}`,
    "Restart=on-failure",
    "RestartSec=10s",
    "RestartPreventExitStatus=78",
    "KillMode=control-group",
    "TimeoutStopSec=30s",
    "LimitNOFILE=65536",
    "StandardOutput=journal",
    "StandardError=journal",
    "",
    "[Install]",
    "WantedBy=multi-user.target",
    "",
  ].join("\n");
}

export function renderCoordinatorUnit(input: CoordinatorUnitInput): string {
  assertUserOrGroup("user", input?.user);
  assertUserOrGroup("group", input?.group);
  assertAbsolutePath("nodePath", input?.nodePath);
  assertAbsolutePath("installDir", input?.installDir);
  assertAbsolutePath("envFile", input?.envFile);
  assertHost(input?.host);
  assertPort(input?.port);
  if (input.webDist !== undefined) assertAbsolutePath("webDist", input.webDist);
  if (input.withWorker !== undefined && typeof input.withWorker !== "boolean") {
    throw new ServiceUnitValidationError("withWorker", "must be a boolean");
  }

  const installDir = input.installDir;
  const description = assertDescription(input.unitDescription, DEFAULT_COORDINATOR_DESCRIPTION);

  const command = [input.nodePath, `${installDir}/dist/index.js`, "cluster", "start", "--host", input.host, "--port", String(input.port)];
  if (input.webDist !== undefined) command.push("--web-dist", input.webDist);
  if (input.withWorker === true) command.push("--worker");

  return renderUnitText({
    description,
    user: input.user,
    group: input.group,
    installDir,
    envFile: input.envFile,
    execStart: command.join(" "),
  });
}

export function renderWorkerUnit(input: WorkerUnitInput): string {
  assertUserOrGroup("user", input?.user);
  assertUserOrGroup("group", input?.group);
  assertAbsolutePath("nodePath", input?.nodePath);
  assertAbsolutePath("installDir", input?.installDir);
  assertAbsolutePath("envFile", input?.envFile);
  if (input.coordinatorUrl !== undefined) {
    assertSafeText("coordinatorUrl", input.coordinatorUrl);
    if (!COORDINATOR_URL_PATTERN.test(input.coordinatorUrl) || input.coordinatorUrl.includes("@")) {
      throw new ServiceUnitValidationError("coordinatorUrl", "must be a ws:// or wss:// URL without credentials");
    }
  }

  const installDir = input.installDir;
  const description = assertDescription(input.unitDescription, DEFAULT_WORKER_DESCRIPTION);

  const command = [input.nodePath, `${installDir}/dist/index.js`, "node", "start"];
  if (input.coordinatorUrl !== undefined) command.push("--coordinator", input.coordinatorUrl);

  return renderUnitText({
    description,
    user: input.user,
    group: input.group,
    installDir,
    envFile: input.envFile,
    execStart: command.join(" "),
  });
}

/**
 * Product-mode service, distinct from the legacy cluster/node CLI units above.
 * This only renders a unit. Stopping the product still cancels active work;
 * callers must establish a separate, verified drain before a controlled stop.
 */
export function renderProductUnit(input: ProductUnitInput): string {
  assertUserOrGroup("user", input?.user);
  assertUserOrGroup("group", input?.group);
  assertAbsolutePath("nodePath", input?.nodePath);
  assertAbsolutePath("installDir", input?.installDir);
  assertAbsolutePath("envFile", input?.envFile);
  if (typeof input.releaseId !== "string" || !/^[a-f0-9]{40}$/.test(input.releaseId)) {
    throw new ServiceUnitValidationError("releaseId", "must be a full lowercase Git commit ID");
  }
  const dependencies = input.afterServices ?? [];
  if (!Array.isArray(dependencies) || dependencies.some(name =>
    typeof name !== "string" || !/^[A-Za-z0-9][A-Za-z0-9_.@-]*\.service$/.test(name) || name.includes(".."))) {
    throw new ServiceUnitValidationError("afterServices", "must contain only safe systemd service names");
  }
  const description = assertDescription(input.unitDescription, "Nash Agents product service");
  return [
    "# Product service; establish a verified drain before stopping it.",
    "# Release is declared here; independently verify the running artifact.",
    "[Unit]",
    `Description=${description} (${input.releaseId})`,
    `After=network-online.target${dependencies.length ? ` ${dependencies.join(" ")}` : ""}`,
    "Wants=network-online.target",
    // Product CLI currently returns 78 even when PostgreSQL is temporarily down.
    // Do not suppress retries for that status or exhaust a short start limit.
    "StartLimitIntervalSec=0",
    "",
    "[Service]",
    "Type=simple",
    `User=${input.user}`,
    `Group=${input.group}`,
    `WorkingDirectory=${input.installDir}`,
    `EnvironmentFile=${input.envFile}`,
    `ExecStart=${input.nodePath} ${input.installDir}/dist/index.js start --service`,
    "Restart=on-failure",
    "RestartSec=30s",
    "KillMode=control-group",
    // The stop gate (/stop) already refuses to stop without a verified drain, so a
    // legitimate shutdown is fast. Bound the timeout anyway: an unbounded wait would
    // leave a stuck unit in "deactivating" forever and block maintenance.
    "TimeoutStopSec=300s",
    "LimitNOFILE=65536",
    "StandardOutput=journal",
    "StandardError=journal",
    "",
    "[Install]",
    "WantedBy=multi-user.target",
    "",
  ].join("\n");
}
